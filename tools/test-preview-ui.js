'use strict'
const assert = require('node:assert/strict')
const vm = require('node:vm')
const { createServer, parse, render, runtime, fixture, patch, css, handlers } = require('./preview-ui')

async function main() {
  const s = { ...fixture('default'), scenario: 'default', dark: false, app: { globalData: {} }, timerId: 0 }
  runtime(s)
  assert.equal(vm.runInContext('typeof process', s.context), 'undefined')
  assert.equal(vm.runInContext('typeof require', s.context), 'undefined')
  assert.throws(() => vm.runInContext('Function("return 1")()', s.context), /Code generation/)
  const template = `<block wx:for="{{rows}}" wx:for-item="group" wx:for-index="gi"><view wx:for="{{group}}" wx:for-item="row" wx:for-index="ri" wx:if="{{row.n > 1}}" class="{{gi}} a {{ri}}" data-item="{{row}}" bindtap="pick"><text wx:if="{{row.n > 3}}">high</text> <text wx:elif="{{row.n > 2}}">middle &amp; safe</text> <text wx:else>{{row.label}}</text></view></block>`
  const html = render(s, parse(template), { rows: [[{ n: 1 }, { n: 2, label: '<img onerror="x"> & safe' }], [{ n: 3 }, { n: 4 }]] })
  assert.equal((html.match(/data-event="pick"/g) || []).length, 3)
  assert.match(html, /class="0 a 1"/)
  assert.match(html, /&lt;img onerror=&quot;x&quot;&gt; &amp; safe/)
  assert.match(html, /middle &amp; safe/)
  assert.match(html, /high/)
  assert.doesNotMatch(html, /<block|wx:|<img/)
  assert.deepEqual([...handlers(parse(template))], ['pick'])
  const data = {}; patch(data, { 'sheet.note': 'saved', 'rows[0].name': 'first' })
  assert.deepEqual(data, { sheet: { note: 'saved' }, rows: [{ name: 'first' }] })
  assert.throws(() => patch(data, { '__proto__.oops': true }), /Unsafe/)
  assert.equal(css('page {padding:30rpx} .text > text {color:red}', false), 'body {padding:calc(30 * 100vw / 750)} .text > span {color:red}')
  assert.match(css('@media (prefers-color-scheme: dark){page{color:white}}', false), /@media not all/)
  assert.equal(new Date(s.now).getFullYear(), 2026)
  assert.equal(s.storage.txs_v1.length, 9)
  assert.ok(s.storage.txs_v1.every(t => t.amount > 0 && t.ym === t.day.slice(0, 7)))
  assert.equal(new Set(s.storage.txs_v1.map(t => t.ym)).size, 2)

  const server = createServer()
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve) })
  const origin = 'http://127.0.0.1:' + server.address().port
  async function get(page, scenario = 'default', dark = 0) {
    const response = await fetch(`${origin}/?page=${page}&scenario=${scenario}&dark=${dark}`)
    const text = await response.text(); assert.equal(response.status, 200, text); return text
  }
  async function post(page, method, dataset = {}, detail = {}, scenario = 'default') {
    const response = await fetch(origin + '/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ page, scenario, method, dataset, detail }) })
    const result = await response.json(); assert.equal(response.status, 200, JSON.stringify(result)); return result
  }
  const pending = html => JSON.parse(html.match(/data-resolve="([^"]+)"/)[1].replace(/&quot;/g, '"'))
  try {
    for (const scenario of ['empty', 'default', 'joined', 'vip']) for (const page of ['home', 'index', 'list', 'report']) {
      const html = await get(page, scenario)
      assert.match(html, /浏览器适配预览 · 示例数据 · 非微信模拟器/)
      assert.match(html, new RegExp(`data-page="${page}"`))
      assert.doesNotMatch(html.split('<main id="preview-root">')[1].split('</main>')[0], /wx:if|wx:for|\[object Object\]|{{/)
      if (page === 'home') assert.match(html, scenario === 'empty' ? /0\.00/ : /261\.50/)
      if (page === 'list' && scenario === 'joined') assert.match(html, /小林/)
      if (page === 'report') assert.equal(/class="upsell"/.test(html), scenario !== 'vip')
    }
    assert.match(await get('home', 'default', 1), /color-scheme:dark/)
    let result = await post('index', 'toggleRefund', {}, { value: false })
    assert.match(result.html, /当前：按到账日计入收入/)
    await post('index', 'toggleRefund', {}, { value: true })
    await post('index', 'pickTheme', { key: 'amber' })
    assert.match(await get('home'), /theme-amber/)
    const prior = s.storage.txs_v1.at(-1).ym
    result = await post('home', 'pickMonth', {}, { value: prior })
    assert.match(result.html, /124\.00/)
    await post('home', 'currentMonth')
    result = await post('report', 'setBudget')
    assert.match(result.html, /月度预算是会员功能/)
    result = await post('report', '$resolve', {}, { ...pending(result.html), confirm: true })
    assert.equal(result.navigation, '/pages/vip/vip')
    result = await post('report', 'setBudget', {}, {}, 'vip')
    result = await post('report', '$resolve', {}, { ...pending(result.html), confirm: true, content: '4500' }, 'vip')
    assert.match(result.html, /预算 ¥4,500\.00|预算 ¥4500\.00/)
    result = await post('report', 'prevMonth', {}, {}, 'vip')
    assert.match(result.html, /124\.00/)
    result = await post('report', 'nextMonth', {}, {}, 'vip')
    assert.match(result.html, /261\.50/)
    result = await post('home', 'goUncat')
    assert.equal(result.activePage, 'list')
    assert.match(result.html, /街角小铺/)
    assert.doesNotMatch(result.html, /data-id="sample-0"/)
    result = await post('list', 'goBack')
    assert.equal(result.activePage, 'home')
    await post('home', 'goList')
    result = await post('list', 'openSheet', { id: 'sample-0' })
    assert.match(result.html, /午后食堂/)
    result = await post('list', 'editNote')
    result = await post('list', '$resolve', {}, { ...pending(result.html), confirm: true, content: '<unsafe> "sample"' })
    assert.match(result.html, /&lt;unsafe&gt; &quot;sample&quot;/)
    result = await post('list', 'deleteSheetItem')
    await post('list', '$resolve', {}, { ...pending(result.html), confirm: false })
    assert.match(await get('list'), /data-id="sample-0"/)
    result = await post('list', 'deleteSheetItem')
    await post('list', '$resolve', {}, { ...pending(result.html), confirm: true })
    assert.doesNotMatch(await get('list'), /data-id="sample-0"/)
    assert.match(await get('list', 'joined'), /data-id="sample-0"/)
    result = await post('list', 'setScope', { k: 'peer' }, {}, 'joined')
    assert.doesNotMatch(result.html, /data-id="sample-0"/)
    assert.match(result.html, /data-id="sample-1"/)
    result = await post('list', 'onSearch', {}, { value: '影院' }, 'vip')
    assert.match(result.html, /上月影院/)
    assert.doesNotMatch(result.html, /data-id="sample-0"/)
    result = await post('list', 'moreActions')
    assert.match(result.html, /role="dialog"/)
    result = await post('list', '$resolve', {}, { ...pending(result.html), tapIndex: 1 })
    assert.match(result.message, /退款已计入/)
    result = await post('report', 'exportCsv', {}, {}, 'vip')
    assert.match(result.message, /未写入真实剪贴板/)
    result = await post('home', 'doSync', {}, {}, 'joined')
    assert.match(result.html, /PREVIEW_OFFLINE/)
    for (const method of ['refresh', 'setData', 'constructor', 'onLoad', 'goAdd();process.exit()']) {
      const r = await fetch(origin + '/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ page: 'home', method }) })
      assert.equal(r.status, 400)
    }
    for (const file of ['/app.js', '/utils/store.js', '/assets/tabbar/../app.json', '/%2e%2e/secret.txt']) assert.equal((await fetch(origin + file)).status, 404)
    assert.equal((await fetch(origin + '/?page=../../utils/store')).status, 400)
    assert.equal((await fetch(origin + '/action', { method: 'POST', body: '{}' })).status, 415)
    assert.equal((await fetch(origin + '/action', { method: 'POST', headers: { Origin: 'https://example.invalid', 'Content-Type': 'application/json' }, body: '{}' })).status, 403)
    assert.equal((await fetch(origin + '/action', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"dataset":{"__proto__":{}}}' })).status, 400)
    assert.equal((await fetch(origin + '/preview-client.js')).status, 200)
    console.log('Preview tests passed: parser, escaping, 16 page/scenario routes, real logic, dialogs, navigation, state isolation and local-only guards.')
  } finally { await new Promise(resolve => server.close(resolve)) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
